"""Package only a candidate that passed the study's locked confirmation criteria."""
import hashlib
import json
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    study = ROOT / "runs/step3b_smolvlm2_stop"
    result = json.loads((study / "result.json").read_text())
    assert result["status"] == "complete" and result["improvement_passed_locked_criteria"]
    report = result["final_confirmation"]
    selected = report["candidate"]
    checkpoint = Path(selected["checkpoint"])
    run = checkpoint.parent.parent
    assert sha(checkpoint / "adapter_model.safetensors") == selected["adapter_sha256"]
    final, temporary = study / "frozen_reference", study / ".frozen_reference.tmp"
    if final.exists():
        assert json.loads((final / "reference.json").read_text())["source_adapter_sha256"] == selected["adapter_sha256"]
        print(str(final))
        return
    temporary.mkdir(exist_ok=False)
    (temporary / "adapter").mkdir()
    for filename in ("adapter_model.safetensors", "adapter_config.json"):
        shutil.copy2(checkpoint / filename, temporary / "adapter" / filename)
    shutil.copy2(run / "policy_config.json", temporary / "policy_config.json")
    shutil.copytree(run / "processor", temporary / "processor")
    runtime = ("policy/common.py", "policy/smolvlm2.py", "policy/online.py", "policy/stop_reference.py")
    for relative in runtime:
        target = temporary / "source" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / relative, target)
    metadata = {"format": "smolvlm2_stop_reference_v1", "created_utc": datetime.now(timezone.utc).isoformat(),
                "source_checkpoint": str(checkpoint), "source_adapter_sha256": selected["adapter_sha256"],
                "confirmation_passed": True, "confirmation_report_sha256": sha(study / f"confirmation_{report['confirmation_set']}" / "report.json"),
                "decoder": {"family": "add STOP-only logit bias, then argmax over four first-token action scores",
                            "stop_logit_bias": selected["stop_bias"], "action_order": ["STOP", "FORWARD", "LEFT", "RIGHT"]},
                "loader": "policy.stop_reference.StopReference(bundle, device='cuda')",
                "runtime_source_sha256": {relative: sha(ROOT / relative) for relative in runtime},
                "reproducibility": "Native batch-one decoding, live simulator RGB; selected bias is part of policy identity",
                "note": "Prior Step-2/Step-3 reference remains unchanged. No downstream scorer labels generated by this study."}
    (temporary / "reference.json").write_text(json.dumps(metadata, indent=2) + "\n")
    shutil.copy2(study / "result.json", temporary / "study_result.json")
    checks = {str(path.relative_to(temporary)): sha(path) for path in sorted(temporary.rglob("*")) if path.is_file()}
    (temporary / "file_sha256.json").write_text(json.dumps(checks, indent=2) + "\n")
    temporary.rename(final)
    print(str(final))


if __name__ == "__main__":
    main()
